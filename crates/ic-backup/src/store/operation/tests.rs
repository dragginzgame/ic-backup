//! Replacement facts only: no fake IC effects, filesystem durability or certificate claims.
//! Spent/uncertain reservation cases adapt the retained submission lesson from
//! frozen legacy 4ae087fad8c23de712aa60bf569bde4b2b932651, submission/mod.rs and
//! tests/http_boundary/mod.rs. The actual transport matrix remains with that owner.
use super::*;

const INTENT: &[u8] = b"approved intent";
fn allowance() -> Allowance {
    Allowance {
        signatures: 30,
        network: 90,
        observations: 3,
        evidence: 8 * 1024 * 1024,
        signer_network: 2,
        request_bytes: 1024,
        result_bytes: 4096,
    }
}
fn reference(bytes: &[u8]) -> ReferenceRecord {
    ReferenceRecord {
        bytes: bytes.len().try_into().unwrap(),
        sha256: *BackupDigest::compute(bytes).as_bytes(),
    }
}
fn read(bytes: &[u8], a: Allowance) -> Journal {
    Journal::read(bytes, INTENT, a).unwrap()
}
fn append(bytes: &mut Vec<u8>, a: Allowance, fact: FactRecord) -> Journal {
    let frame = read(bytes, a).candidate(fact).unwrap();
    bytes.extend(frame);
    read(bytes, a)
}
fn facts(step: Step) -> [FactRecord; 4] {
    [
        FactRecord::CallReserved {
            step,
            reference_ns: 100,
        },
        FactRecord::CallPrepared {
            step,
            request: reference(b"original signed request"),
        },
        FactRecord::CallSubmitted { step },
        FactRecord::CallResult {
            step,
            result: reference(b"original certified response"),
        },
    ]
}
fn complete_history(a: Allowance) -> Vec<u8> {
    let mut bytes = Journal::initial(INTENT, a).unwrap();
    for step in [
        Step::InitialStatus,
        Step::ListSnapshots,
        Step::TakeSnapshot,
        Step::Metadata,
        Step::Data(0),
    ] {
        for fact in facts(step) {
            append(&mut bytes, a, fact);
        }
    }
    append(&mut bytes, a, FactRecord::MaterializationStarted);
    for fact in facts(Step::FinalStatus) {
        append(&mut bytes, a, fact);
    }
    append(
        &mut bytes,
        a,
        FactRecord::PublishReady {
            completed_at_ns: 200,
        },
    );
    bytes
}

#[test]
fn created_bytes_and_domain_have_an_independent_vector() {
    // Independently assembled with Perl Digest::SHA, little-endian pack("V") and
    // the literal JSON below; not generated by the Rust journal encoder.
    let expected = "280000007b2273657175656e6365223a302c2266616374223a7b226b696e64223a2263726561746564227d7d7061e61c7be12cf27909b5044ae7d876a9f629575906f76a5737c6d981c8f6d5";
    let bytes = Journal::initial(INTENT, allowance()).unwrap();
    assert_eq!(
        bytes.iter().map(|b| format!("{b:02x}")).collect::<String>(),
        expected
    );
    assert!(matches!(
        Journal::read(bytes.as_slice(), b"different approval", allowance()),
        Err(LedgerError::Chain)
    ));
    let previous =
        crate::store::operation::framing::initial_bytes(INTENT, allowance().evidence).unwrap();
    assert!(matches!(
        Journal::read(previous.as_slice(), INTENT, allowance()),
        Err(LedgerError::Chain)
    ));
    assert!(matches!(
        Journal::read([].as_slice(), INTENT, allowance()),
        Err(LedgerError::Empty)
    ));
}

#[test]
fn signing_and_submission_reservations_cannot_be_repeated_or_refunded() {
    let a = allowance();
    let step = Step::InitialStatus;
    let mut bytes = Journal::initial(INTENT, a).unwrap();
    for fact in facts(step) {
        let state = append(&mut bytes, a, fact.clone());
        assert_eq!((state.signatures, state.network), (1, 3));
        assert_eq!(state.calls[0].update.reference_ns, 100);
        assert!(state.candidate(fact).is_err());
        assert!(
            state
                .candidate(FactRecord::CallReserved {
                    step,
                    reference_ns: 900
                })
                .is_err()
        );
        // The whole original request/result/frame allowance stays reserved at
        // every prefix, including before signer output and after terminal evidence.
        assert_eq!(state.evidence_reserved, 76 + 4 * (16384 + 36) + 1024 + 4096);
        assert_eq!(state.frames_reserved, 5);
        assert_eq!(read(&bytes, a), state);
    }
}

#[test]
fn no_submission_without_original_request_and_no_replacing_retained_bytes() {
    let a = allowance();
    let step = Step::InitialStatus;
    let mut bytes = Journal::initial(INTENT, a).unwrap();
    let state = append(&mut bytes, a, facts(step)[0].clone());
    for bad in [
        facts(step)[2].clone(),
        facts(step)[3].clone(),
        facts(Step::ListSnapshots)[0].clone(),
    ] {
        assert!(matches!(state.candidate(bad), Err(LedgerError::Transition)));
    }
    let state = append(&mut bytes, a, facts(step)[1].clone());
    for length in [0, 1025] {
        assert!(
            state
                .candidate(FactRecord::CallPrepared {
                    step,
                    request: ReferenceRecord {
                        bytes: length,
                        sha256: [4; 32]
                    }
                })
                .is_err()
        );
    }
    let state = append(&mut bytes, a, facts(step)[2].clone());
    assert!(
        state
            .candidate(FactRecord::CallResult {
                step,
                result: ReferenceRecord {
                    bytes: 4097,
                    sha256: [8; 32]
                }
            })
            .is_err()
    );
    let state = append(&mut bytes, a, facts(step)[3].clone());
    assert!(
        state
            .candidate(FactRecord::CallResult {
                step,
                result: reference(b"replacement")
            })
            .is_err()
    );
}

#[test]
fn one_observation_has_its_own_spending_and_can_never_resubmit_the_update() {
    let a = allowance();
    let step = Step::InitialStatus;
    let mut bytes = Journal::initial(INTENT, a).unwrap();
    for fact in &facts(step)[..3] {
        append(&mut bytes, a, fact.clone());
    }
    let observation = [
        FactRecord::ObservationReserved {
            step,
            reference_ns: 300,
        },
        FactRecord::ObservationPrepared {
            step,
            request: reference(b"signed read-state"),
        },
        FactRecord::ObservationSubmitted { step },
        FactRecord::ObservationResult {
            step,
            certificate: reference(b"observation certificate"),
        },
    ];
    for fact in observation {
        let state = append(&mut bytes, a, fact.clone());
        assert_eq!(
            (state.signatures, state.network, state.observations),
            (2, 6, 1)
        );
        assert_eq!(state.calls[0].update.reference_ns, 100);
        assert_eq!(
            state.calls[0].observation.as_ref().unwrap().reference_ns,
            300
        );
        assert!(state.calls[0].update.result.is_none());
        assert!(state.candidate(facts(step)[2].clone()).is_err());
        assert!(state.candidate(fact).is_err());
        assert!(
            state
                .candidate(FactRecord::ObservationReserved {
                    step,
                    reference_ns: 500
                })
                .is_err()
        );
    }
    // Evidence authentication belongs to the fixed capture procedure. The facts
    // reader does not call an unknown/processing observation a successful update.
    assert!(read(&bytes, a).calls[0].update.result.is_none());
}

#[test]
fn surviving_reply_does_not_refund_an_interrupted_observation() {
    let a = allowance();
    let step = Step::InitialStatus;
    let mut bytes = Journal::initial(INTENT, a).unwrap();
    for fact in &facts(step)[..3] {
        append(&mut bytes, a, fact.clone());
    }
    append(
        &mut bytes,
        a,
        FactRecord::ObservationReserved {
            step,
            reference_ns: 300,
        },
    );
    let state = append(&mut bytes, a, facts(step)[3].clone());
    assert_eq!(
        (state.signatures, state.network, state.observations),
        (2, 6, 1)
    );
    assert!(
        state.calls[0]
            .observation
            .as_ref()
            .unwrap()
            .request
            .is_none()
    );
    assert!(
        state
            .candidate(FactRecord::ObservationPrepared {
                step,
                request: reference(b"late signer")
            })
            .is_err()
    );
    assert!(
        state
            .candidate(FactRecord::CallResult {
                step,
                result: reference(b"duplicate")
            })
            .is_err()
    );
}

#[test]
fn original_limits_apply_before_signing_and_remain_exhausted_on_reopen() {
    for a in [
        Allowance {
            signatures: 1,
            ..allowance()
        },
        Allowance {
            network: 3,
            ..allowance()
        },
        Allowance {
            evidence: 76 + 4 * (16384 + 36) + 1024 + 4096,
            ..allowance()
        },
    ] {
        let mut bytes = Journal::initial(INTENT, a).unwrap();
        for fact in facts(Step::InitialStatus) {
            append(&mut bytes, a, fact);
        }
        let original = bytes.clone();
        for _ in 0..2 {
            let state = read(&bytes, a);
            let before = state.clone();
            assert!(
                state
                    .candidate(facts(Step::ListSnapshots)[0].clone())
                    .is_err()
            );
            assert_eq!(state, before);
        }
        assert_eq!(bytes, original);
    }
    let a = Allowance {
        observations: 0,
        ..allowance()
    };
    let mut bytes = Journal::initial(INTENT, a).unwrap();
    for fact in &facts(Step::InitialStatus)[..3] {
        append(&mut bytes, a, fact.clone());
    }
    assert!(
        read(&bytes, a)
            .candidate(FactRecord::ObservationReserved {
                step: Step::InitialStatus,
                reference_ns: 200
            })
            .is_err()
    );
}

#[test]
fn fixed_order_materialization_and_closed_completion_refuse_extra_work() {
    let a = allowance();
    let mut bytes = Journal::initial(INTENT, a).unwrap();
    assert!(
        read(&bytes, a)
            .candidate(facts(Step::TakeSnapshot)[0].clone())
            .is_err()
    );
    for step in [
        Step::InitialStatus,
        Step::ListSnapshots,
        Step::TakeSnapshot,
        Step::Metadata,
    ] {
        for fact in facts(step) {
            append(&mut bytes, a, fact);
        }
    }
    for fact in [
        facts(Step::Data(1))[0].clone(),
        facts(Step::FinalStatus)[0].clone(),
        FactRecord::MaterializationStarted,
    ] {
        assert!(read(&bytes, a).candidate(fact).is_err());
    }
    for fact in facts(Step::Data(0)) {
        append(&mut bytes, a, fact);
    }
    assert!(
        read(&bytes, a)
            .candidate(facts(Step::Data(2))[0].clone())
            .is_err()
    );
    let state = append(&mut bytes, a, FactRecord::MaterializationStarted);
    assert!(state.candidate(FactRecord::MaterializationStarted).is_err());
    assert!(state.candidate(facts(Step::Data(1))[0].clone()).is_err());
    assert!(
        state
            .candidate(FactRecord::PublishReady {
                completed_at_ns: 200
            })
            .is_err()
    );
    for fact in facts(Step::FinalStatus) {
        append(&mut bytes, a, fact);
    }
    assert!(
        read(&bytes, a)
            .candidate(FactRecord::PublishReady { completed_at_ns: 0 })
            .is_err()
    );
    let state = append(
        &mut bytes,
        a,
        FactRecord::PublishReady {
            completed_at_ns: 200,
        },
    );
    assert_eq!(state.completed_at_ns, Some(200));
    assert_eq!(
        (
            state.signatures,
            state.network,
            state.count,
            state.frames_reserved
        ),
        (6, 18, 27, 27)
    );
    for fact in [
        FactRecord::Created,
        FactRecord::MaterializationStarted,
        FactRecord::PublishReady {
            completed_at_ns: 201,
        },
        facts(Step::InitialStatus)[0].clone(),
    ] {
        assert!(state.candidate(fact).is_err());
    }
}

#[test]
fn partial_tails_and_changed_frames_never_project_unused_authority() {
    let a = allowance();
    let bytes = complete_history(a);
    let mut boundary = 0;
    while boundary < bytes.len() {
        let size =
            u32::from_le_bytes(bytes[boundary..boundary + 4].try_into().unwrap()) as usize + 36;
        for offset in 1..size {
            assert!(matches!(
                Journal::read(&bytes[..boundary + offset], INTENT, a),
                Err(LedgerError::Truncated)
            ));
        }
        boundary += size;
        read(&bytes[..boundary], a);
    }
    for at in [4, 15, 55, bytes.len() - 1] {
        let mut changed = bytes.clone();
        changed[at] ^= 1;
        assert!(matches!(
            Journal::read(changed.as_slice(), INTENT, a),
            Err(LedgerError::Chain)
        ));
    }
}

#[test]
fn hashed_unknown_duplicate_and_noncanonical_records_are_not_extensions() {
    let a = allowance();
    let prefix = Journal::initial(INTENT, a).unwrap();
    let state = read(&prefix, a);
    for payload in [
        br#"{"sequence":1,"fact":{"kind":"created"}}"#.as_slice(),
        br#"{"sequence":2,"fact":{"kind":"call_reserved","step":"initial_status","reference_ns":100}}"#,
        br#"{"sequence":1,"fact":{"kind":"data_accepted","step":{"data":0}}}"#,
        br#"{"sequence":1,"sequence":1,"fact":{"kind":"created"}}"#,
        br#"{"sequence":1,"fact":{"kind":"call_reserved","step":"initial_status","reference_ns":100,"extra":true}}"#,
        br#"{ "sequence":1,"fact":{"kind":"call_reserved","step":"initial_status","reference_ns":100}}"#,
    ] {
        let mut bytes = prefix.clone();
        bytes.extend(encode_frame(state.head, payload).unwrap());
        assert!(matches!(Journal::read(bytes.as_slice(), INTENT, a), Err(LedgerError::Transition)));
    }
}
